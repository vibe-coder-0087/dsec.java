public class assignmentoperator {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;
        int c = 30;
        System.out.println("Assignment Operator");
        a += 5; // a = a + 5
        System.out.println("a += 5: " + a);
        b -= 5; // b = b - 5
        System.out.println("b -= 5: " + b);
        c *= 2; // c = c * 2
        System.out.println("c *= 2: " + c);
    }
}
