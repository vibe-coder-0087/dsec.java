public class ternaryoperator {
    public static void main(String args[])
    {
        int a=10;
        int b=11;
        int c;
        System.out.println("TERNARY OPERATOR");
        c=(a<b)?a:b;
        System.out.println("c: " + c);
        c=(a!=b)?a:b;
        System.out.println("c: " + c);
        c=(a>b)?a:b;
        System.out.println("c: " + c);

    }
}
