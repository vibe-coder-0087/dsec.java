public class unaryoperator {
    public static void main(String args[])
    {
        int a=10;
        System.out.println("UNARY OPERATOR");
        System.out.println("a: " + a);
        System.out.println("++a: " + ++a);
        System.out.println("--a: " + --a);
        System.out.println("a++: " + a++);
        System.out.println("a--: " + a--);
        System.out.println("-a: " + -a);
        System.out.println("+a: " + +a);
    }
}
